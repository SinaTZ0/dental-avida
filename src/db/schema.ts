/*===== Database Schema =====*/
// Single source of truth for tables, read by Drizzle Kit (`drizzle.config.ts`) and the runtime client (`Db`,
// `src/server/db.server.ts`). Every change ships as a migration: `pnpm db:generate --name <what-changed>`, then `pnpm
// db:migrate` (docs/backend/architecture.md, Database).

/*===== Columns =====*/
/**
 * A moment in time, stored as `timestamp with time zone`. Use it for every time column: the plain `timestamp` type
 * keeps no zone, so `now()` and psql would read and write it in whatever zone the database's session is set to.
 */
function timestamptz(name: string) {
  return timestamp(name, { withTimezone: true });
}

/*===== Auth (Better-Auth) =====*/
// Mirrors Better-Auth's core tables. Table and column names must match its model and field
// names (`user`, `emailVerified`, …) because the Drizzle adapter looks them up by key, so keep
// them in sync with `@better-auth/core` when upgrading. IDs are strings generated by Better-Auth.

export const user = pgTable("user", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").notNull().default(false),
  image: text("image"),
  // Plain text instead of pg enums: allowed values live in `src/lib/user-constants.ts`. Never set from the client
  // (`input: false` in `auth.server.ts`).
  role: text("role").notNull().default("user"),
  status: text("status").notNull().default("active"),
  createdAt: timestamptz("created_at").notNull().defaultNow(),
  updatedAt: timestamptz("updated_at")
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
});

